/// Что процесс (или все процессы правила) делал в сети — и что из этого
/// прошло через наши руки.
///
/// Два источника, и смысл именно в их сравнении. `connects`, `v6` и
/// `local` — со слоя сокетов: процесс попросил соединение. `led` — из
/// наших решений: начало соединения пришло к нам пакетом и было уведено.
/// Если первое больше второго, часть соединений процесса под правилом
/// прошла мимо нас, и это надо видеть числом, а не узнавать по жалобе
/// «не открывается». До этих счётчиков о работе правила говорили первые
/// восемь строк журнала за жизнь службы — на девятом соединении она
/// слепла.
#[derive(Default, Clone, Copy, Debug, PartialEq, Eq)]
pub struct Traffic {
    /// Соединений TCP наружу по IPv4 — тех, что мы обязаны были увести.
    pub connects: u64,
    /// Из них уведено в туннель.
    pub led: u64,
    /// Начал соединений этого процесса, которые прошли через наши руки с
    /// домашним адресом и были отпущены как чужие. Это и есть утечка: у
    /// процесса под правилом такое бывает, только если в миг соединения он
    /// ещё не был опознан. Считается у всех процессов, потому что именно
    /// неопознанный и станет своим позже.
    pub past: u64,
    /// Соединений, открытых процессом до того, как он попал под правило
    /// (правило добавили при открытом приложении). В счёт правила не идут
    /// и утечкой не считаются, но живут дальше мимо туннеля.
    pub before: u64,
    /// Соединений по IPv6. Путь B их не ведёт вовсе; на машине, где IPv6
    /// маршрутизируется, каждое такое — мимо туннеля.
    pub v6: u64,
    /// Соединений в свою сеть: их не уводим намеренно.
    pub local: u64,
    /// Портов UDP, уведённых в туннель.
    pub udp: u64,
}

impl Traffic {
    fn add(&mut self, other: &Traffic) {
        self.connects += other.connects;
        self.led += other.led;
        self.past += other.past;
        self.before += other.before;
        self.v6 += other.v6;
        self.local += other.local;
        self.udp += other.udp;
    }

    /// Соединений, начала которых к нам не пришло вовсе: процесс соединение
    /// попросил, а пакета с домашним адресом на нашем слое не было. Мимо
    /// туннеля такое уйти не могло — всё, что уходит с домашнего адреса,
    /// проходит через нас и попадает либо в `led`, либо в `past`. Остаются
    /// два объяснения: начало соединения забрала другая программа
    /// перехвата, стоящая раньше нас, или соединение не состоялось.
    ///
    /// Это находка живой проверки. На машине разработки под правилом до нас
    /// дошло одно начало соединения winget из двенадцати. Без правила в
    /// таблице ядра рядом с соединением winget (домашний адрес → сервер)
    /// пять раз из шести стояло парное: `redirector.exe` чужого VPN-клиента,
    /// со своего сокета на адресе туннеля, на тот же сервер. Он стоит
    /// раньше нас и забирает начало соединения себе. Пока счётчик был один,
    /// такие соединения выглядели как «не уведено», то есть как утечка.
    ///
    /// Куда чужая программа отправит соединение дальше, отсюда не видно:
    /// за эти соединения служба не ручается, она лишь знает, что с
    /// домашнего адреса пакет самого приложения не уходил.
    pub fn unseen(&self) -> u64 {
        self.connects.saturating_sub(self.led).saturating_sub(self.past)
    }

    /// Одной строкой, для журнала — теми же словами, что и в `status`.
    pub fn describe(&self) -> String {
        vpnsplit_core::describe_traffic(
            self.connects,
            self.led,
            self.past,
            self.before,
            self.v6,
            self.local,
            self.udp,
        )
    }

    fn is_empty(&self) -> bool {
        *self == Traffic::default()
    }

    /// Процесс только что попал под правило уже работающим: всё, что он
    /// открыл до этого, откладывается в `before`, а счёт правила начинается
    /// с нуля. Возвращает, сколько отложено.
    fn set_aside(&mut self) -> u64 {
        let opened = self.connects + self.v6;
        *self = Traffic { before: self.before + opened, ..Traffic::default() };
        opened
    }
}

/// Куда отнести соединение: наружу по IPv4, в свою сеть или IPv6.
///
/// Сокет двойного режима соединяется с адресом IPv4, записанным как IPv6
/// (`::ffff:a.b.c.d`), и на проводе это обычный IPv4 — его и считаем так.
fn note(traffic: &mut Traffic, remote: std::net::IpAddr) {
    let v4 = match remote {
        std::net::IpAddr::V4(address) => Some(address),
        std::net::IpAddr::V6(address) => address.to_ipv4_mapped(),
    };
    match v4 {
        Some(address) if ipv4::stays_home(address) => traffic.local += 1,
        Some(_) => traffic.connects += 1,
        None => traffic.v6 += 1,
    }
}

