    #[test]
    fn what_was_not_led_is_the_difference_and_never_negative() {
        let quiet = Traffic { connects: 5, led: 5, ..Traffic::default() };
        assert_eq!(quiet.unseen(), 0);
        let leaking = Traffic { connects: 5, led: 3, ..Traffic::default() };
        assert_eq!(leaking.unseen(), 2);
        // Уведено больше, чем открыто, бывает: соединение началось раньше,
        // чем мы стали считать. Это не «минус два мимо».
        let early = Traffic { connects: 1, led: 3, ..Traffic::default() };
        assert_eq!(early.unseen(), 0);
        // «Не увели» делится надвое: отпущено нашими руками — утечка; не
        // дошло до нас вовсе — забрал кто-то раньше.
        let mixed = Traffic { connects: 12, led: 1, past: 2, ..Traffic::default() };
        assert_eq!((mixed.past, mixed.unseen()), (2, 9));
        assert_eq!(Traffic { connects: 1, past: 3, ..Traffic::default() }.unseen(), 0);
        // Сложение по процессам правила.
        let mut total = quiet;
        total.add(&leaking);
        total.add(&mixed);
        assert_eq!((total.connects, total.led, total.past, total.unseen()), (22, 9, 2, 11));
        assert!(Traffic::default().is_empty());
        assert!(!leaking.is_empty());
    }

