/// Фильтр статической ручки. `tcp.Syn and not tcp.Ack` — только самое
/// начало соединения, без ответных SYN-ACK.
const SYN_FILTER: &str = "outbound and tcp and tcp.Syn and not tcp.Ack and not loopback";

/// Фильтр ручки имён: запросы наружу и ответы обратно.
const DNS_FILTER: &str = "udp and not loopback and \
                          ((outbound and udp.DstPort == 53) or (inbound and udp.SrcPort == 53))";

/// Фильтр ручки UDP: **весь** исходящий UDP наружу, кроме имён (ими занята
/// своя ручка) и своей сети.
///
/// Почему весь, а не только наш, как у TCP. У TCP есть SYN: начало
/// соединения ловится узким фильтром и держится в руках, пока перестраивается
/// фильтр потоков. У UDP первый же пакет несёт данные, а узнать о потоке
/// заранее нечем — замерено 22.11.2026: событие «поток открыт» опережает
/// первый пакет на 95–206 мкс, а перестройка фильтра стоит до 3121. Значит
/// либо первый пакет каждого потока уходит домашним адресом, либо в руках
/// оказывается весь исходящий UDP. Первое — молчаливая утечка; выбрано
/// второе. Цена на этой машине: 8 пакетов в секунду в среднем, 140 на пике,
/// то есть 0,03% и 0,46% ядра.
///
/// Свою сеть и рассылки отсекает сам фильтр, а не код: это самый шумный UDP
/// на машине (обнаружение устройств, имена соседей), и платить за него
/// 33 мкс на пакет незачем.
const UDP_OUT_FILTER: &str = "outbound and udp and not loopback and udp.DstPort != 53 \
     and ip.DstAddr < 224.0.0.0 \
     and (ip.DstAddr < 10.0.0.0 or ip.DstAddr > 10.255.255.255) \
     and (ip.DstAddr < 172.16.0.0 or ip.DstAddr > 172.31.255.255) \
     and (ip.DstAddr < 192.168.0.0 or ip.DstAddr > 192.168.255.255) \
     and (ip.DstAddr < 169.254.0.0 or ip.DstAddr > 169.254.255.255)";

/// Фильтр обратного направления UDP: только то, что пришло на адрес туннеля
/// — любого из тех, по которым мы что-то ведём. Туда приходят ответы нашим
/// потокам — и ещё приложениям пути A, но тех мы узнаём по порту и не
/// трогаем.
fn udp_in_filter(tunnels: &[Ipv4Addr]) -> String {
    format!("inbound and udp and not loopback and udp.SrcPort != 53 and {}", to_any_of(tunnels))
}

/// «Пришло на один из этих адресов» — условием фильтра WinDivert.
fn to_any_of(addresses: &[Ipv4Addr]) -> String {
    let each: Vec<String> =
        addresses.iter().map(|address| format!("ip.DstAddr == {address}")).collect();
    format!("({})", each.join(" or "))
}

/// Как часто перепроверять хозяина порта по таблице ядра.
///
/// Хозяин берётся из события сокета, и в обычной жизни перепроверка не
/// нужна. Она здесь на случай потерянного события: очередь событий не
/// бесконечна. Обращение к таблице стоит 537 мкс (замерено, 499 сокетов),
/// поэтому делать его чаще, чем раз в несколько секунд на порт, незачем.
const UDP_RECHECK: Duration = Duration::from_secs(5);

/// Сколько порт считается нашим без исходящих пакетов. Обратное
/// направление узнаётся по порту, и держать запись вечно нельзя: порт
/// достанется другому процессу. Пять минут — с запасом против обычных
/// сроков, на которые рассчитывают программы за домашним роутером.
const UDP_IDLE: Duration = Duration::from_secs(300);

/// Сколько ждать события сокета, если пакет пришёл раньше, чем мы о сокете
/// узнали. В ядре событие всегда раньше пакета (замерено: не меньше 95 мкс),
/// но читают их два разных потока, и наш мог ещё не успеть.
const UDP_PATIENCE: Duration = Duration::from_millis(2);

/// Сколько ждать события о запуске процесса после просьбы отдать события
/// сейчас. Это потолок, а не обычная цена: всё это время начало соединения
/// (а для UDP — весь исходящий UDP машины) стоит у нас в руках. Сколько
/// ждать приходится на деле, пишется в итог: «ожиданий запуска».
///
/// Замерено в бою (22.11.2026, девять ожиданий): обычное — 0,3–0,8 мс. Но
/// первые события после запуска службы обрабатываются медленнее — каждое
/// сверяется со снимком системы, — и три ожидания вышли 21, 22 и 42 мс.
/// При прежнем потолке в 50 мс от утечки это отделяло 8 мс. Потолок
/// поднят: ошибиться в сторону лишнего ожидания — задержка одного
/// соединения, в сторону нехватки — соединение мимо туннеля.
const START_PATIENCE: Duration = Duration::from_millis(250);

/// Сколько держать память о запросе имени, чтобы узнать ответ. Запросы
/// живут секунды: системный разрешатель переспрашивает через секунду, так
/// что десяти хватает с запасом, а висеть дольше незачем.
const DNS_MEMORY: Duration = Duration::from_secs(10);

/// Сколько помнить, кто спрашивал имя. Служба кеша шлёт запрос сразу, но
/// переспрашивает через секунду, две, четыре — и на каждом повторе заказчик
/// должен находиться.
const DNS_ASKED: Duration = Duration::from_secs(10);

/// Сколько ждать заказчика из списка, когда чужой заказчик уже известен.
///
/// Событие «приложение спросило имя» пишется раньше, чем запрос уходит на
/// провод, а после просьбы отдать события доходит за доли миллисекунды
/// (так замерено на событиях процессов: 0,1 мс при одном наборе буферов).
/// Но «всё, что было записано, уже у нас» узнать нельзя — можно только
/// подождать. Столько платит каждый запрос имени от постороннего
/// приложения; ошибиться в меньшую сторону — имя приложения из списка у
/// домашнего провайдера.
///
/// Замерено на живой службе (22.11.2026, шестнадцать ожиданий): просьба
/// отдать события — 40–236 мкс, заказчик объявляется через 70–287 мкс
/// после запроса. Два миллисекунды — семикратный запас к худшему.
const DNS_SETTLE: Duration = Duration::from_millis(2);

/// Сколько ждать заказчика, не засыпая: поток уступает процессор и тут же
/// смотрит снова.
///
/// Первая версия ждала на таймере и платила за это втрое больше, чем
/// собиралась: Windows будит по таймеру раз в 15,6 мс, и «подождать 4 мс»
/// выходило в 14–15. Все посторонние запросы имён задерживались на эти 15
/// мс ни за что. Событие приходит за доли миллисекунды, так что короткое
/// ожидание честнее провести на ногах; на таймер уходит только редкий
/// случай, когда заказчика нет вовсе.
const DNS_SPIN: Duration = Duration::from_millis(2);

/// Сколько ждать, если заказчика нет вовсе. Такого быть не должно — имя
/// всегда кто-то спросил, — поэтому ждём дольше: это либо событие в пути,
/// либо запрос, который служба кеша сделала сама.
///
/// Первый живой прогон (22.11.2026) стоял с потолком 30 мс, и заказчики
/// объявлялись через 7–20 мс после запроса — до потолка оставалась треть.
/// Не дождаться здесь — значит отпустить домой имя приложения из списка,
/// а дождаться лишнего — задержать редкий запрос без заказчика; потолок
/// поднят с запасом.
const DNS_PATIENCE: Duration = Duration::from_millis(250);

/// В какой срок заказчик из списка, объявившийся после решения «домой»,
/// считается опоздавшим к тому самому запросу, а не новым вопросом.
const DNS_LATE: Duration = Duration::from_millis(50);

/// Как часто заново спрашивать у диспетчера служб, в каком процессе живёт
/// служба кеша имён.
const DNS_CACHE_RECHECK: Duration = Duration::from_secs(60);

/// Имя как ключ: без учёта регистра и без точки в конце.
fn dns_key(name: &str) -> String {
    name.trim_end_matches('.').to_lowercase()
}

/// Кто какие имена спрашивал — по событиям `DNS-Client`.
///
/// Имя для приложения спрашивает служба кеша, одна на всю машину, и на
/// проводе запрос принадлежит ей. Заказчика называет только событие 3006:
/// оно пишется в контексте того, кто спросил. Раньше эта привязка
/// «опаздывала» и в туннель уходил весь DNS машины; опаздывала она по той
/// же причине, что и события процессов, — буферы по процессорам, — и
/// лечится тем же: один набор буферов и просьба отдать события сейчас.
#[derive(Default)]
struct Asked {
    names: std::collections::HashMap<String, Vec<(u32, Instant)>>,
    /// Имена, по которым недавно решено «домой»: чтобы заметить заказчика
    /// из списка, объявившегося после решения.
    sent_home: std::collections::HashMap<String, Instant>,
    /// Кандидаты в опоздавшие: заказчик и имя. Наш ли заказчик, решает
    /// поток пакетов — поток событий ждать не должен.
    late: Vec<(u32, String)>,
}

impl Asked {
    fn note(&mut self, name: &str, pid: u32, now: Instant) {
        let key = dns_key(name);
        if self.sent_home.get(&key).is_some_and(|at| now.duration_since(*at) < DNS_LATE) {
            self.late.push((pid, key.clone()));
        }
        let askers = self.names.entry(key).or_default();
        askers.retain(|(_, at)| now.duration_since(*at) < DNS_ASKED);
        askers.push((pid, now));
        // Имён на машине спрашивают десятки в минуту; чистка раз в
        // несколько сотен записей держит карту маленькой без таймера.
        if self.names.len() > 512 {
            self.names
                .retain(|_, askers| askers.iter().any(|(_, at)| now.duration_since(*at) < DNS_ASKED));
            self.sent_home.retain(|_, at| now.duration_since(*at) < DNS_ASKED);
        }
    }

    /// Кто спрашивал это имя недавно; каждый заказчик — один раз.
    fn askers(&self, name: &str, now: Instant) -> Vec<u32> {
        let mut pids: Vec<u32> = self
            .names
            .get(&dns_key(name))
            .map(|askers| {
                askers
                    .iter()
                    .filter(|(_, at)| now.duration_since(*at) < DNS_ASKED)
                    .map(|(pid, _)| *pid)
                    .collect()
            })
            .unwrap_or_default();
        pids.sort_unstable();
        pids.dedup();
        pids
    }

    fn went_home(&mut self, name: &str, now: Instant) {
        self.sent_home.insert(dns_key(name), now);
        // Чистится и здесь, а не только в `note`: «домой» уходят и имена
        // посторонних программ со своим разрешателем, о которых событий
        // нет вовсе, и `names` может не дорасти до чистки никогда.
        if self.sent_home.len() > 512 {
            self.sent_home.retain(|_, at| now.duration_since(*at) < DNS_ASKED);
        }
    }

    /// Чистка по таймеру: всё, что старше срока, уже ни на что не влияет.
    fn tidy(&mut self, now: Instant) {
        self.names.retain(|_, askers| {
            askers.retain(|(_, at)| now.duration_since(*at) < DNS_ASKED);
            !askers.is_empty()
        });
        self.sent_home.retain(|_, at| now.duration_since(*at) < DNS_ASKED);
    }
}

/// Чьё имя: решение по одному запросу на проводе.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum NameOwner {
    /// Запрос шлёт само приложение из списка, со своего сокета.
    OwnSocket,
    /// Запрос шлёт служба кеша по заказу приложения из списка.
    Asked,
    /// Имя спросил кто-то посторонний.
    Foreign,
    /// Заказчика не нашлось.
    Nobody,
}

impl NameOwner {
    fn ours(self) -> bool {
        matches!(self, NameOwner::OwnSocket | NameOwner::Asked)
    }
}

/// Кого уводить.
///
/// Два вида, и разница между ними не в придирчивости, а в происхождении.
/// `Rules` — это список пользователя, и сравнение там точное, как в самой
/// политике: правило не должно прихватывать лишнее. `Needle` живёт только
/// для опытов из консоли, где удобно написать «curl» и не искать полный
/// путь; в бою такой цели не бывает.
pub enum Watch {
    Rules(Vec<AppTarget>),
    Needle(String),
}

impl Watch {
    pub fn describe(&self) -> String {
        match self {
            Watch::Rules(targets) if targets.is_empty() => "список пуст".to_owned(),
            Watch::Rules(targets) => targets
                .iter()
                .map(|target| target.display_name())
                .collect::<Vec<_>>()
                .join(", "),
            Watch::Needle(needle) => format!("подстрока «{needle}»"),
        }
    }

    fn is_empty(&self) -> bool {
        matches!(self, Watch::Rules(targets) if targets.is_empty())
    }

    /// Надо ли спрашивать у процесса имя пакета. Это отдельный системный
    /// вызов на каждый запуск процесса в системе, и платить его стоит
    /// только если в списке действительно есть пакеты.
    fn needs_package(&self) -> bool {
        match self {
            Watch::Rules(targets) => targets.iter().any(AppTarget::needs_package),
            Watch::Needle(_) => true,
        }
    }

    /// Какому правилу подходит процесс — его имя для родословной. `None`
    /// — никакому.
    fn matching(&self, image: Option<&std::path::Path>, package: Option<&str>) -> Option<String> {
        match self {
            Watch::Rules(targets) => targets
                .iter()
                .find(|target| target.matches(image, package))
                .map(AppTarget::key),
            Watch::Needle(needle) => {
                let hit = |text: &str| text.to_lowercase().contains(needle);
                (image.is_some_and(|image| hit(&image.to_string_lossy()))
                    || package.is_some_and(hit))
                .then(|| needle.clone())
            }
        }
    }

    /// Имена всех нынешних правил: по ним при правке списка решается, кто
    /// из родословной остаётся.
    fn rule_keys(&self) -> std::collections::HashSet<String> {
        match self {
            Watch::Rules(targets) => targets.iter().map(AppTarget::key).collect(),
            Watch::Needle(needle) => std::iter::once(needle.clone()).collect(),
        }
    }
}

/// Кому сообщать, что изменился набор правил, под которыми кто-то есть.
/// Получает полный нынешний набор имён правил (`AppTarget::key`).
pub type Listener = Box<dyn Fn(&[String]) + Send + Sync>;

/// Кому сообщать, какие программы оказываются под правилом: имя правила и
/// путь к образу принятого процесса. Каждая пара сообщается один раз.
///
/// Нужно для запретов на время простоя службы: правило называет одну
/// программу, а ведёт и её потомков с другими образами. У правила на
/// значок-запускатель настоящая программа — вообще не та, что в правиле, и
/// узнать её можно только так: увидев, кого запускатель запустил.
///
/// Третье — работает ли эта же программа прямо сейчас и вне правил. Такой
/// сеть на время простоя закрывать нельзя: запрет стоит на образ и оставил
/// бы без неё всех, кто пользуется программой сам по себе.
pub type Learner = Box<dyn Fn(&str, &std::path::Path, bool) + Send + Sync>;

/// В каком процессе сейчас работает служба Windows с таким именем.
fn service_process(name: &str) -> Option<u32> {
    use windows_service::service::ServiceAccess;
    use windows_service::service_manager::{ServiceManager, ServiceManagerAccess};
    let manager =
        ServiceManager::local_computer(None::<&str>, ServiceManagerAccess::CONNECT).ok()?;
    let service = manager.open_service(name, ServiceAccess::QUERY_STATUS).ok()?;
    service.query_status().ok()?.process_id
}

/// Кто из процессов с тем же образом работает вне правил: ни сам не под
/// присмотром, ни один из его предков по снимку.
///
/// Предки проверяются не из осторожности, а по необходимости. Приложение
/// заводит потомков пачкой, события об их запуске идут друг за другом, и
/// в миг, когда разбирается первое, остальные уже видны в снимке, но в
/// родословную ещё не приняты. Суди мы по одной родословной, главная
/// программа приложения считалась бы «запущенной и сама по себе» — из-за
/// собственных братьев.
///
/// Номер родителя в снимке мог достаться чужому процессу; тогда ошибка
/// будет в сторону «свой», то есть запрет останется. Это безопасная
/// сторона: лишний запрет виден и снимается, лишняя свобода — нет.
fn strangers(
    candidates: &[u32],
    parents: &std::collections::HashMap<u32, u32>,
    supervised: impl Fn(u32) -> bool,
) -> Vec<u32> {
    candidates
        .iter()
        .copied()
        .filter(|&pid| {
            let mut at = pid;
            // Предел — от петель: номера переиспользуются, и цепочка
            // «родителей» по снимку может замкнуться.
            for _ in 0..32 {
                if supervised(at) {
                    return false;
                }
                match parents.get(&at) {
                    Some(&parent) if parent != 0 && parent != at => at = parent,
                    _ => break,
                }
            }
            true
        })
        .collect()
}

/// Где мы находимся относительно туннеля. Пересматривается при каждом
/// изменении сети — именно от этого зависит, переписываем мы пакет,
/// выбрасываем его или не трогаем вовсе.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Place {
    /// Обычное положение: домашний адрес подменяется адресом туннеля.
    Rewrite { home: routes::Route, tunnel: Ipv4Addr },
    /// Туннеля нет. Подменять не на что, поэтому пакеты наших приложений
    /// выбрасываются: отказ в связи вместо утечки.
    Blocked { home: routes::Route },
    /// Трогать нечего: либо система и так ходит через туннель (на его
    /// интерфейсе маршруты `0.0.0.0/1` и `128.0.0.0/1`), либо наружу
    /// вообще нет маршрута. В обоих случаях и подменять нечего, и
    /// выбрасывать нечего.
    Idle,
}

impl Place {
    /// Заодно пересчитывает дорожки: у каждого правила свой туннель, и
    /// адреса их меняются вместе с сетью. В самом положении остаётся
    /// туннель «на всякий случай» — для того, о чём неизвестно, чьё оно.
    fn look(lanes: &mut Lanes) -> Place {
        let adapters = iface::list().unwrap_or_default();
        let auto = iface::find_tunnel(None).ok().and_then(|adapter| adapter.ipv4);
        lanes.resolve(auto, |name| {
            adapters.iter().find(|a| a.name == name && a.usable()).and_then(|a| a.ipv4)
        });
        match (routes::best_route(Ipv4Addr::new(1, 1, 1, 1)), lanes.fallback()) {
            (None, _) => Place::Idle,
            (Some(home), Some(_)) if lanes.is_tunnel(home.source) => Place::Idle,
            (Some(home), Some(tunnel)) => Place::Rewrite { home, tunnel },
            (Some(home), None) => Place::Blocked { home },
        }
    }

    /// Домашний адрес и интерфейс. `None` означает «ничего не делаем».
    fn home(&self) -> Option<routes::Route> {
        match self {
            Place::Rewrite { home, .. } | Place::Blocked { home } => Some(*home),
            Place::Idle => None,
        }
    }

    fn tunnel(&self) -> Option<Ipv4Addr> {
        match self {
            Place::Rewrite { tunnel, .. } => Some(*tunnel),
            _ => None,
        }
    }

    fn describe(&self) -> String {
        match self {
            Place::Rewrite { home, tunnel } => {
                format!("{} (интерфейс {}) → {tunnel}", home.source, home.interface_index)
            }
            Place::Blocked { .. } => {
                "туннеля нет, соединения выбранных приложений отклоняются".to_owned()
            }
            Place::Idle => "подменять нечего: система и так ходит через туннель".to_owned(),
        }
    }
}

