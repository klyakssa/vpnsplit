//! Путь B целиком: приложение и всё, что оно запускает, уходит в туннель.
//!
//! Задача, которой нет в языке фильтров WinDivert: **на слое пакетов не
//! видно, чей это процесс.** Отсюда три ручки, у каждой своё дело.
//!
//! 1. **Статическая** — `outbound and tcp and tcp.Syn`: через
//!    пользовательский режим проходят только начала соединений, это десятки
//!    пакетов в секунду. Её главное свойство не опознание, а **удержание**:
//!    перехваченный пакет исчезает из сети, пока мы его не вернём. Значит
//!    SYN можно держать в руках сколько нужно — определить хозяина по
//!    таблице соединений ядра, перестроить второй фильтр и только потом
//!    отпустить. Без удержания была бы гонка: соединение успело бы
//!    установиться с домашнего адреса.
//! 2. **Динамическая** — перечисляет пятёрки живых потоков наших
//!    приложений и переписывает их пакеты. Чужие пакеты в пользовательский
//!    режим не попадают вовсе: в Этапе 11b замерено, что перехват стоит
//!    33 мкс на пакет, и платить это за весь трафик машины нельзя.
//! 3. **Наблюдение за потоками** — только чтение, чтобы снимать правило по
//!    закрытию потока.
//!
//! Кого уводить, решает набор номеров процессов: само приложение и все его
//! потомки. Родословная ведётся по событиям запуска (там есть номер
//! родителя), а не по снимку системы: номера процессов переиспользуются, и
//! к моменту снимка номер родителя может указывать уже на другую программу.
//!
//! Процессы, запущенные не приложением, а по его просьбе чужой службой, в
//! набор не попадают — это сознательно вынесено за рамки.
//!
//! **Если туннель пропадает, подменять адрес не на что.** Тогда пакеты
//! наших приложений выбрасываются: приложение получает отказ в связи, а не
//! молчаливый выход через домашний интернет. Это та же мысль, что в
//! kill-switch пути A, только здесь она достаётся даром — пакет и так у
//! нас в руках, достаточно его не возвращать.

